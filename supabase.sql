-- THE LUGA HOUSE – SIWANI COLLECTIONS
-- Run this in Supabase SQL Editor.
-- Then create your first Auth user in Authentication > Users and set that user's
-- profiles.role = 'admin' below.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'customer' check (role in ('customer','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text unique not null,
  sort_order int not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  price numeric(12,2) not null default 0,
  compare_price numeric(12,2),
  image text,
  description text,
  sizes text[] not null default '{}',
  featured boolean not null default false,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.store_settings (
  id int primary key default 1 check (id=1),
  site_title text not null default 'The Luga House – Siwani Collections',
  announcement text not null default '✨ New arrivals • Order directly on WhatsApp',
  facebook text default '', instagram text default '', youtube text default '',
  tiktok text default '', twitter text default '', linkedin text default '',
  updated_at timestamptz not null default now()
);

insert into public.categories(name,sort_order) values
 ('Men',1),('Ladies',2),('Kiddos',3),('Accessories',4)
on conflict (name) do nothing;
insert into public.store_settings(id) values (1) on conflict (id) do nothing;

alter table public.profiles enable row level security;
alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.store_settings enable row level security;

-- Helper: current signed-in user is an admin.
create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin');
$$;

-- Public catalogue read.
drop policy if exists "public read active categories" on public.categories;
create policy "public read active categories" on public.categories for select using (active=true or public.is_admin());
drop policy if exists "public read active products" on public.products;
create policy "public read active products" on public.products for select using (active=true or public.is_admin());
drop policy if exists "public read settings" on public.store_settings;
create policy "public read settings" on public.store_settings for select using (true);

-- Admin writes.
drop policy if exists "admins write categories" on public.categories;
create policy "admins write categories" on public.categories for all using (public.is_admin()) with check (public.is_admin());
drop policy if exists "admins write products" on public.products;
create policy "admins write products" on public.products for all using (public.is_admin()) with check (public.is_admin());
drop policy if exists "admins write settings" on public.store_settings;
create policy "admins write settings" on public.store_settings for all using (public.is_admin()) with check (public.is_admin());
drop policy if exists "user read own profile" on public.profiles;
create policy "user read own profile" on public.profiles for select using (id=auth.uid());
drop policy if exists "admins manage profiles" on public.profiles;
create policy "admins manage profiles" on public.profiles for all using (public.is_admin()) with check (public.is_admin());

-- Realtime publication. If the table is already in the publication, the ALTER may error;
-- in that case skip that table's line.
alter publication supabase_realtime add table public.products;
alter publication supabase_realtime add table public.categories;
alter publication supabase_realtime add table public.store_settings;

